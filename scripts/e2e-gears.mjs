import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://localhost:5299/?ride=gaisberg&sim=1&at=3000&watts=250');
await page.waitForFunction(() => window.__ready, null, { timeout: 120000 });
await page.waitForTimeout(2000);
const read = () => page.locator('.gearbox').first().textContent();
console.log('start:', await read());
for (let i = 0; i < 4; i++) await page.keyboard.press('BracketRight');
await page.waitForTimeout(300); console.log('after 4 up:', await read());
for (let i = 0; i < 20; i++) await page.keyboard.press('BracketLeft');
await page.waitForTimeout(300); console.log('after 20 down:', await read());
await page.keyboard.press('Minus'); await page.waitForTimeout(300);
console.log('difficulty:', await page.locator('.hud-power .sub').textContent());
for (let i = 0; i < 6; i++) await page.keyboard.press('BracketRight');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/gears.png' });
console.log(errs.length ? errs.join('\n') : 'no errors');
await browser.close();

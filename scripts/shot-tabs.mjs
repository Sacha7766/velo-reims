import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto(`http://localhost:${process.env.PORT ?? 5199}/`);
await page.waitForTimeout(2500);
await page.getByRole('radio', { name: 'Workout' }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/h2-workout.png' });
await page.getByRole('button', { name: /Change workout|Choose a workout/ }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: 'shots/h2-picker.png' });
await page.keyboard.press('Escape');
await page.locator('.dev-chips').click();
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/h2-devices.png' });
await page.getByRole('button', { name: 'Done' }).click();
await page.getByRole('button', { name: 'Train', exact: true }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: 'shots/h2-train.png' });
await page.getByRole('button', { name: 'Settings', exact: true }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: 'shots/h2-settings.png' });
await page.getByRole('button', { name: 'History', exact: true }).click();
await page.waitForTimeout(1200);
await page.screenshot({ path: 'shots/h2-history.png' });
console.log(errs.length ? errs.join('\n') : 'no errors');
await browser.close();

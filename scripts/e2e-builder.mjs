import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() !== 'log') errors.push(m.type() + ': ' + m.text().slice(0, 200)); });
page.on('requestfailed', (r) => errors.push('failed: ' + r.url().slice(0, 120)));
await page.goto('http://localhost:5199/');
await page.getByRole('button', { name: 'Draw a route' }).click();
await page.waitForSelector('.builder .maplibregl-canvas', { timeout: 20000 });
await page.fill('.builder .search input', 'Pöstlingberg, Linz');
await page.keyboard.press('Enter');
await page.waitForTimeout(4500);
const box = await page.locator('.builder .map').boundingBox();
await page.mouse.click(box.x + box.width * 0.62, box.y + box.height * 0.62);
await page.waitForTimeout(400);
await page.mouse.click(box.x + box.width * 0.45, box.y + box.height * 0.4);
await page.waitForTimeout(4000);
console.log('stats:', await page.locator('.builder .r-stats').textContent().catch(() => 'none'));
await page.screenshot({ path: 'shots/builder.png' });
console.log(errors.length ? errors.join('\n') : 'no errors');
await browser.close();
